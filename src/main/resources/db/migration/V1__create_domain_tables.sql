CREATE TABLE company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corp_code VARCHAR(8) NOT NULL,
    stock_code VARCHAR(6),
    name VARCHAR(200) NOT NULL,
    dart_modified_on DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_company_corp_code UNIQUE (corp_code),
    CONSTRAINT uk_company_stock_code UNIQUE (stock_code),
    CONSTRAINT ck_company_corp_code CHECK (corp_code ~ '^[0-9]{8}$'),
    CONSTRAINT ck_company_stock_code CHECK (stock_code IS NULL OR stock_code ~ '^[0-9A-Z]{6}$'),
    CONSTRAINT ck_company_name CHECK (name ~ '[^[:space:]]')
);

CREATE TABLE watched_company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    monitoring_enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_watched_company_company UNIQUE (company_id),
    CONSTRAINT fk_watched_company_company FOREIGN KEY (company_id) REFERENCES company (id)
);

CREATE TABLE disclosure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    rcept_no VARCHAR(14) NOT NULL,
    report_name VARCHAR(500) NOT NULL,
    receipt_date DATE NOT NULL,
    disclosure_type VARCHAR(32),
    initial_import BOOLEAN NOT NULL,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_disclosure_rcept_no UNIQUE (rcept_no),
    CONSTRAINT fk_disclosure_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT ck_disclosure_rcept_no CHECK (rcept_no ~ '^[0-9]{14}$'),
    CONSTRAINT ck_disclosure_report_name CHECK (report_name ~ '[^[:space:]]'),
    CONSTRAINT ck_disclosure_type CHECK (disclosure_type IN (
        'PERIODIC', 'MATERIAL_EVENT', 'ISSUANCE', 'SHAREHOLDING', 'OTHER',
        'EXTERNAL_AUDIT', 'FUND', 'ASSET_SECURITIZATION', 'EXCHANGE', 'FAIR_TRADE'))
);
CREATE INDEX ix_disclosure_company_date ON disclosure (company_id, receipt_date DESC, id DESC);

CREATE TABLE notification_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watched_company_id BIGINT NOT NULL,
    disclosure_type VARCHAR(32) NOT NULL,
    channel VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_notification_rule_target UNIQUE (watched_company_id, disclosure_type, channel),
    CONSTRAINT fk_notification_rule_watched FOREIGN KEY (watched_company_id)
        REFERENCES watched_company (id) ON DELETE CASCADE,
    CONSTRAINT ck_notification_rule_type CHECK (disclosure_type IN (
        'PERIODIC', 'MATERIAL_EVENT', 'ISSUANCE', 'SHAREHOLDING', 'OTHER',
        'EXTERNAL_AUDIT', 'FUND', 'ASSET_SECURITIZATION', 'EXCHANGE', 'FAIR_TRADE')),
    CONSTRAINT ck_notification_rule_channel CHECK (channel IN ('EMAIL'))
);

CREATE TABLE notification_delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disclosure_id BIGINT NOT NULL,
    channel VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    attempt_count INTEGER NOT NULL,
    last_attempt_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(2000),
    sent_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uk_notification_delivery_target UNIQUE (disclosure_id, channel),
    CONSTRAINT fk_notification_delivery_disclosure FOREIGN KEY (disclosure_id) REFERENCES disclosure (id),
    CONSTRAINT ck_notification_delivery_channel CHECK (channel IN ('EMAIL')),
    CONSTRAINT ck_notification_delivery_status CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_notification_delivery_version CHECK (version >= 0),
    CONSTRAINT ck_notification_delivery_state CHECK (
        (status = 'PENDING' AND attempt_count = 0 AND last_attempt_at IS NULL AND sent_at IS NULL AND last_error IS NULL)
        OR (status = 'SENDING' AND attempt_count > 0 AND last_attempt_at IS NOT NULL AND sent_at IS NULL AND last_error IS NULL)
        OR (status = 'SENT' AND attempt_count > 0 AND last_attempt_at IS NOT NULL AND sent_at IS NOT NULL AND last_error IS NULL)
        OR (status = 'FAILED' AND attempt_count > 0 AND last_attempt_at IS NOT NULL AND sent_at IS NULL
            AND last_error IS NOT NULL AND last_error ~ '[^[:space:]]')
    )
);
CREATE INDEX ix_notification_delivery_status_created ON notification_delivery (status, created_at);
